"""Writes the report-reconciliation parity fixture shared by the backend and the browser (DECISIONS D-32).

The browser mirrors floodnet/access/events.py in frontend-react/src/lib/roadAccess.js so the map and the reports page
agree with the router before any request. This script runs the BACKEND rules on a fixed list of cases (Agent C T1-T9
plus the QA parity cases A-I) and writes inputs + backend results to
frontend-react/src/lib/reconciliation_parity.json. Two tests then pin it from both sides:
  backend/tests/test_reconciliation_parity.py   - the backend still produces exactly this file
  frontend-react/src/lib/roadReports.test.mjs   - the browser mirror produces the same statuses
Run from backend/:  .venv/Scripts/python scripts/reconciliation_parity.py
"""
from __future__ import annotations

import json
from pathlib import Path

from floodnet.access.events import ClosureBook, parse_events

OUT = Path(__file__).resolve().parents[2] / "frontend-react" / "src" / "lib" / "reconciliation_parity.json"


def ev(eid, kind, r, a=None, tier=None):
    e = {"event_id": eid, "seg_id": "x", "kind": kind, "received_t_min": r, "applies_from_t_min": r if a is None else a}
    if tier is not None:
        e["source_tier"] = tier
    return e


CASES = {
    "T1_reopen_without_references": (61, [ev("C1", "closure", 10), ev("R2", "reopen", 60)]),
    "T2_reopen_recorded_before_closure": (30, [ev("C1", "closure", 10), ev("R2", "reopen", 8)]),
    "T3_late_backdated_closure": (35, [ev("C0", "closure", 0), ev("R1", "reopen", 20), ev("C1", "closure", 30, 5)]),
    "T4_full_tie_closure_wins": (30, [ev("R2", "reopen", 10), ev("C1", "closure", 10)]),
    "T5_public_reopen_vs_operator_closure": (15, [ev("C1", "closure", 10, tier="OPERATOR"), ev("R2", "reopen", 12, tier="PUBLIC")]),
    "T6_public_closure_unconfirmed": (10, [ev("C1", "closure", 0, tier="PUBLIC")]),
    "T7_scheduled_reopen_before_its_time": (25, [ev("C1", "closure", 10), ev("R2", "reopen", 20, 40)]),
    "T8_stale_field_team_closure": (100, [ev("C1", "closure", 0, tier="FIELD_TEAM")]),
    "T9_authority_needs_authority": (10, [ev("C1", "closure", 0, tier="AUTHORITY"), ev("R2", "reopen", 5, tier="FIELD_TEAM"), ev("R3", "reopen", 6, tier="AUTHORITY")]),
    "A_public_closure_then_operator_reopen": (30, [ev("C1", "closure", 10, tier="PUBLIC"), ev("R2", "reopen", 20, tier="OPERATOR")]),
    "B_lowercase_public_tier": (30, [ev("C1", "closure", 10, tier="public")]),
    "C_reopen_lifts_one_rejected_by_other": (30, [ev("C1", "closure", 0, tier="OPERATOR"), ev("C2", "closure", 1, tier="AUTHORITY"), ev("R3", "reopen", 5, tier="OPERATOR")]),
    "D_public_closure_public_reopen": (30, [ev("C1", "closure", 10, tier="PUBLIC"), ev("R2", "reopen", 12, tier="PUBLIC")]),
    "E_backdated_closure_h2": (35, [ev("C0", "closure", 0), ev("R1", "reopen", 20), ev("C1", "closure", 30, 5)]),
    "G_scheduled_reopen_lifts_later": (45, [ev("C1", "closure", 10), ev("R2", "reopen", 20, 40)]),
    "I_future_closure": (5, [ev("C1", "closure", 10, 0)]),
}


def backend_result(t: float, raw: list[dict]) -> dict:
    book = ClosureBook(parse_events(raw), t)
    ann = {a["event_id"]: a for a in book.annotated()}
    closed = book.closure_at("x", t)
    unconf = book.unconfirmed_during("x", t, t)
    return {
        "closed_by": closed.event_id if closed else None,
        "unconfirmed": unconf.event_id if unconf else None,
        "status": {k: v["status"] for k, v in sorted(ann.items())},
        "lifts": {k: list(v.get("lifts") or []) for k, v in sorted(ann.items())},
        "contested_by": {k: list(v.get("contested_by") or []) for k, v in sorted(ann.items())},
        "stale": {k: bool(v.get("stale")) for k, v in sorted(ann.items())},
    }


def build() -> dict:
    return {
        "_about": "Generated by backend/scripts/reconciliation_parity.py from floodnet/access/events.py. Do not edit by hand.",
        "cases": {name: {"decision_t_min": t, "events": raw, "expected": backend_result(t, raw)} for name, (t, raw) in CASES.items()},
    }


if __name__ == "__main__":
    OUT.write_text(json.dumps(build(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
