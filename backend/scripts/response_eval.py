"""Evidence for docs/RESPONSE_EVALUATION.md: the scripted replay with both routing methods, planned on one run and
judged against another. SIMULATED. Writes docs/validation/response_eval_<forecast>_vs_<outcome>.json.

Run (from backend/):
  .venv/Scripts/python scripts/response_eval.py [forecast_scenario] [outcome_scenario] [horizon_min]
      the hand-written DEMO_SCRIPT (as before); add --csv to also write the per-case rows
      (export_rows/export_csv: one row per road x decision x lead, tagged SIMULATED) next to the JSON.
  ... --seeds N       the first N DEV_SEEDS through evaluate_many -> response_eval_<f>_vs_<o>_seeds.json
  ... --held-out      every HELD_OUT_SEEDS seed (final report only) -> response_eval_<f>_vs_<o>_heldout_seeds.json
Every replay on the real pilot costs seconds; N seeds cost N times the single run. Files are regenerated by this
script only, never edited by hand.
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone

from floodnet import config
from floodnet.access.road_status import Forecast, build_context, load_dem_mask
from floodnet.api import state
from floodnet.response.evaluate import DEV_SEEDS, HELD_OUT_SEEDS, evaluate, evaluate_many, export_csv, export_rows


def series_of(res) -> Forecast:
    streets = {sid: [float(f.street_depth_m.get(sid, 0.0)) * 100.0 for f in res.frames] for sid in {s for f in res.frames for s in f.street_depth_m}}
    return Forecast(tuple(f.t_s / 60.0 for f in res.frames), streets, label=f"{res.scenario} run {res.run_id}")


def _inputs(forecast_id: str, outcome_id: str, horizon: int):
    p = state.get_pilot()
    roads = p["roads"]
    ctx = build_context(state.street_fn_for(roads, p["terrain"].grid).cells, load_dem_mask())
    f = series_of(state.run_scenario(forecast_id, {"mode": "none"}, horizon))
    o = f if outcome_id == forecast_id else series_of(state.run_scenario(outcome_id, {"mode": "none"}, horizon))
    return roads, ctx, f, o


def _write(path, out: dict) -> None:
    out["generated_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    path.write_text(json.dumps(out, indent=1), encoding="utf-8")
    print("wrote", path)


def main(forecast_id="heavy", outcome_id="cloudburst", horizon=180, *, write_csv=False) -> dict:
    roads, ctx, f, o = _inputs(forecast_id, outcome_id, horizon)
    out = evaluate(roads, ctx, f, o)
    out.pop("ledgers")
    cases = out.pop("prediction_cases")              # too large for the JSON; exported as CSV on request
    base = config.REPO_DIR / "docs" / "validation" / f"response_eval_{forecast_id}_vs_{outcome_id}"
    if write_csv:
        rows = export_rows({**out, "prediction_cases": cases})
        base.with_name(base.name + "_rows.csv").write_text(export_csv(rows), encoding="utf-8")
        print("wrote", base.with_name(base.name + "_rows.csv"), f"({len(rows)} rows)")
    _write(base.with_suffix(".json"), out)
    print(f"forecast={forecast_id} outcome={outcome_id}")
    for k, v in out["comparison"].items():
        print(f"  {k:32s} {v}")
    pq = out["prediction"]
    for m in ("arrival_aware", "current_status"):
        print(f"  prediction {m:15s} {pq[m]}")
    print("  blocking flagged incl. uncertain:", pq["share_of_blocking_flagged_incl_uncertain"], "| cases", pq["arrival_aware"]["cases"], "unknown excluded", pq["unknown_cases_excluded"])
    for mode in ("arrival", "current"):
        print(f"  {mode} steps:", [(s["t_min"], s["dispatched"], s["served"], s["unmet"]) for s in out["modes"][mode]["steps"]])
        print(f"  {mode} blocked examples:", out["modes"][mode]["metrics"]["blocked_examples"][:3])
    return out


def main_seeds(forecast_id="heavy", outcome_id="cloudburst", horizon=180, *, seeds, seed_set: str) -> dict:
    """evaluate_many over `seeds` (DEV or HELD_OUT); the JSON records which set was used."""
    roads, ctx, f, o = _inputs(forecast_id, outcome_id, horizon)
    out = evaluate_many(roads, ctx, f, o, list(seeds), horizon_t_min=horizon)
    out["seed_set"] = seed_set
    suffix = "_seeds.json" if seed_set == "DEV" else "_heldout_seeds.json"
    _write(config.REPO_DIR / "docs" / "validation" / f"response_eval_{forecast_id}_vs_{outcome_id}{suffix}", out)
    print(f"forecast={forecast_id} outcome={outcome_id} seeds={seed_set} {list(seeds)}")
    print("  information check:", "ok" if out["information_check"]["ok"] else out["information_check"]["violations"])
    for name, agg in out["aggregate"].items():
        print(f"  {name:60s} mean {agg['mean']:.4g}  min {agg['min']:.4g}  max {agg['max']:.4g}  std {agg['std']:.4g}")
    return out


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("forecast", nargs="?", default="heavy")
    ap.add_argument("outcome", nargs="?", default="cloudburst")
    ap.add_argument("horizon", nargs="?", type=int, default=180)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--seeds", type=int, metavar="N", help=f"replay the first N of DEV_SEEDS ({DEV_SEEDS.start}..{DEV_SEEDS.stop - 1})")
    g.add_argument("--held-out", action="store_true", help=f"replay HELD_OUT_SEEDS ({HELD_OUT_SEEDS.start}..{HELD_OUT_SEEDS.stop - 1}); final report only")
    ap.add_argument("--csv", action="store_true", help="single-script run: also write the per-case rows CSV")
    a = ap.parse_args()
    if a.held_out:
        main_seeds(a.forecast, a.outcome, a.horizon, seeds=HELD_OUT_SEEDS, seed_set="HELD_OUT")
    elif a.seeds is not None:
        if not 1 <= a.seeds <= len(DEV_SEEDS):
            ap.error(f"--seeds must be between 1 and {len(DEV_SEEDS)}")
        main_seeds(a.forecast, a.outcome, a.horizon, seeds=DEV_SEEDS[:a.seeds], seed_set="DEV")
    else:
        main(a.forecast, a.outcome, a.horizon, write_csv=a.csv)
